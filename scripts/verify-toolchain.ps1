[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

function Require-ExactVersion {
    param(
        [Parameter(Mandatory = $true)][string]$Name,
        [Parameter(Mandatory = $true)][string]$Actual,
        [Parameter(Mandatory = $true)][string]$Expected
    )

    if ($Actual -ne $Expected) {
        throw "$Name version mismatch. Expected $Expected; found $Actual."
    }
}

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$nodeVersion = (& node --version).Trim().TrimStart('v')
$pnpmVersion = (& pnpm --version).Trim()
$pythonVersion = (& python --version 2>&1).Trim()

Require-ExactVersion -Name 'Node.js' -Actual $nodeVersion -Expected '24.19.0'
Require-ExactVersion -Name 'pnpm' -Actual $pnpmVersion -Expected '11.19.0'
Require-ExactVersion -Name 'Python' -Actual $pythonVersion -Expected 'Python 3.12.10'

foreach ($marker in @('.nvmrc', '.python-version', 'requirements.lock')) {
    $path = Join-Path $repoRoot $marker
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        throw "Required toolchain marker is missing: $marker"
    }
}

Require-ExactVersion -Name '.nvmrc' -Actual ((Get-Content -Raw (Join-Path $repoRoot '.nvmrc')).Trim()) -Expected '24.19.0'
Require-ExactVersion -Name '.python-version' -Actual ((Get-Content -Raw (Join-Path $repoRoot '.python-version')).Trim()) -Expected '3.12.10'

$requirementsLock = Get-Content -Raw (Join-Path $repoRoot 'requirements.lock')
if ($requirementsLock -notmatch '(?m)^#\s+This file is autogenerated by pip-compile' -or $requirementsLock -notmatch '\s--hash=sha256:') {
    throw 'requirements.lock is not a pip-compile hash-locked file.'
}

foreach ($relativePackage in @('studio-ui-remotion-verify/package.json', 'oauth-site/worker/package.json')) {
    $packagePath = Join-Path $repoRoot $relativePackage
    $lockPath = Join-Path (Split-Path $packagePath -Parent) 'pnpm-lock.yaml'
    if (-not (Test-Path -LiteralPath $lockPath -PathType Leaf)) {
        throw "pnpm lockfile is missing: $lockPath"
    }

    $package = Get-Content -Raw $packagePath | ConvertFrom-Json
    Require-ExactVersion -Name "$relativePackage packageManager" -Actual $package.packageManager -Expected 'pnpm@11.19.0'
    Require-ExactVersion -Name "$relativePackage engines.node" -Actual $package.engines.node -Expected '>=24.19.0 <25'
}

Write-Output 'TOOLCHAIN_VERIFY=PASS'
